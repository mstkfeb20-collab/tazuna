-- 予約。区分値の意味はコード定義書（S-15）で決め、列の説明からその行を指す
CREATE TABLE RESERVE (
    RESERVENO   CHAR(10)      NOT NULL,
    TOURCODE    CHAR(6)       NOT NULL,
    ADULTCOUNT  NUMERIC(2)    NOT NULL,
    CHILDCOUNT  NUMERIC(2)    NOT NULL,
    SUMPRICE    NUMERIC(10)   NOT NULL,
    REMARKS     VARCHAR(80),
    TRANSFER    CHAR(1)       DEFAULT '0' NOT NULL,
    CONSTRAINT PK_RESERVE PRIMARY KEY (RESERVENO),
    CONSTRAINT FK_RESERVE_TOUR FOREIGN KEY (TOURCODE) REFERENCES TOURINFO (TOURCODE),
    CONSTRAINT CK_RESERVE_COUNT CHECK (ADULTCOUNT >= 1 AND CHILDCOUNT >= 0),
    CONSTRAINT CK_RESERVE_TRANSFER CHECK (TRANSFER IN ('0', '1', '9'))
);
COMMENT ON TABLE  RESERVE IS 'ツアーの予約（トランザクション）';
COMMENT ON COLUMN RESERVE.RESERVENO IS '予約番号';
COMMENT ON COLUMN RESERVE.TOURCODE IS '予約したツアー';
COMMENT ON COLUMN RESERVE.ADULTCOUNT IS '大人人数。お子様だけの予約は受けないため1以上';
COMMENT ON COLUMN RESERVE.CHILDCOUNT IS '子供人数';
COMMENT ON COLUMN RESERVE.SUMPRICE IS '合計金額（円）。予約時のツアー料金で計算した値を保存する';
COMMENT ON COLUMN RESERVE.REMARKS IS '備考（最大80文字）';
COMMENT ON COLUMN RESERVE.TRANSFER IS '振込状況。値の意味は S-15-001/D-05005/1';

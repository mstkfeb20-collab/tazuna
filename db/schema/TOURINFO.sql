-- ツアー情報。テーブル設計書（S-16）には DDL に書けない決定（保持期間・データ量・索引の理由）だけを書く
CREATE TABLE TOURINFO (
    TOURCODE        CHAR(6)       NOT NULL,
    TOURNAME        VARCHAR(100)  NOT NULL,
    DEPARTUREDATE   DATE          NOT NULL,
    ADULTPRICE      NUMERIC(9)    NOT NULL,
    CHILDPRICE      NUMERIC(9)    NOT NULL,
    REMAININGSEATS  NUMERIC(4)    NOT NULL,
    CONSTRAINT PK_TOURINFO PRIMARY KEY (TOURCODE),
    CONSTRAINT CK_TOURINFO_PRICE CHECK (ADULTPRICE >= 0 AND CHILDPRICE >= 0),
    CONSTRAINT CK_TOURINFO_SEATS CHECK (REMAININGSEATS >= 0)
);
COMMENT ON TABLE  TOURINFO IS '販売するツアー（マスタ）';
COMMENT ON COLUMN TOURINFO.TOURCODE IS 'ツアーコード';
COMMENT ON COLUMN TOURINFO.TOURNAME IS 'ツアー名（画面と帳票に出す名前）';
COMMENT ON COLUMN TOURINFO.DEPARTUREDATE IS '出発日';
COMMENT ON COLUMN TOURINFO.ADULTPRICE IS '大人1人の料金（円）';
COMMENT ON COLUMN TOURINFO.CHILDPRICE IS '子供1人の料金（円）';
COMMENT ON COLUMN TOURINFO.REMAININGSEATS IS '残席数。予約の確定で減り、取消で戻る';

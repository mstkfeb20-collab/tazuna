CREATE TABLE REFUND (
    REFUND_NO      CHAR(13)       NOT NULL,
    RESERVE_NO     VARCHAR2(13)   NOT NULL,
    REFUND_AMOUNT  NUMBER(9)      NOT NULL,
    CANCEL_FEE     NUMBER(9)      NOT NULL,
    STATUS         CHAR(1)        DEFAULT '0' NOT NULL,
    CONSTRAINT PK_REFUND PRIMARY KEY (REFUND_NO),
    CONSTRAINT CK_REFUND_STATUS CHECK (STATUS IN ('0', '1'))
);
COMMENT ON TABLE  REFUND IS '返金待ち';
COMMENT ON COLUMN REFUND.REFUND_NO IS '返金番号';
COMMENT ON COLUMN REFUND.RESERVE_NO IS '予約番号';
COMMENT ON COLUMN REFUND.REFUND_AMOUNT IS '返金額（円）';
COMMENT ON COLUMN REFUND.CANCEL_FEE IS '取消料（円）';
COMMENT ON COLUMN REFUND.STATUS IS '返金の状態。値の意味は S-15-001/D-05005/2';

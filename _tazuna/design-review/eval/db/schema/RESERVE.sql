CREATE TABLE RESERVE (
    RESERVE_NO     VARCHAR2(13)    NOT NULL,
    TOUR_CODE      CHAR(8)         NOT NULL,
    MEMBER_NO      CHAR(10)        NOT NULL,
    SUM_PRICE      NUMBER(9)       NOT NULL,
    TRANSFER       CHAR(1)         DEFAULT '0' NOT NULL,
    PAID_AMOUNT    NUMBER(9),
    CANCEL_DATE    DATE,
    CANCEL_REASON  NVARCHAR2(100),
    VERSION        NUMBER(9)       NOT NULL,
    CONSTRAINT PK_RESERVE PRIMARY KEY (RESERVE_NO),
    CONSTRAINT CK_RESERVE_TRANSFER CHECK (TRANSFER IN ('0', '1', '2', '9'))
);
COMMENT ON TABLE  RESERVE IS '予約';
COMMENT ON COLUMN RESERVE.RESERVE_NO IS '予約番号';
COMMENT ON COLUMN RESERVE.TOUR_CODE IS 'ツアーコード';
COMMENT ON COLUMN RESERVE.MEMBER_NO IS '会員番号';
COMMENT ON COLUMN RESERVE.SUM_PRICE IS '合計金額（円）';
COMMENT ON COLUMN RESERVE.TRANSFER IS '振込状況。値の意味は S-15-001/D-05005/1';
COMMENT ON COLUMN RESERVE.PAID_AMOUNT IS '入金額（円）';
COMMENT ON COLUMN RESERVE.CANCEL_DATE IS '取消日';
COMMENT ON COLUMN RESERVE.CANCEL_REASON IS '取消理由（100文字まで）';
COMMENT ON COLUMN RESERVE.VERSION IS '楽観ロックの版番号';

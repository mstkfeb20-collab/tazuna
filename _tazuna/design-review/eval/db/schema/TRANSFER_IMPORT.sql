CREATE TABLE TRANSFER_IMPORT (
    ACCOUNT_DATE  DATE          NOT NULL,
    INQUIRY_NO    CHAR(6)       NOT NULL,
    AMOUNT        NUMBER(10)    NOT NULL,
    PAYER_NAME    VARCHAR2(48)  NOT NULL,
    CONSTRAINT PK_TRANSFER_IMPORT PRIMARY KEY (ACCOUNT_DATE, INQUIRY_NO)
);
COMMENT ON TABLE  TRANSFER_IMPORT IS '振込取込結果';
COMMENT ON COLUMN TRANSFER_IMPORT.ACCOUNT_DATE IS '勘定日';
COMMENT ON COLUMN TRANSFER_IMPORT.INQUIRY_NO IS '照会番号';
COMMENT ON COLUMN TRANSFER_IMPORT.AMOUNT IS '振込金額（円）';
COMMENT ON COLUMN TRANSFER_IMPORT.PAYER_NAME IS '振込依頼人名';
